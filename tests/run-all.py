#!/usr/bin/env python3
"""Domain OS: ONE test runner for the whole project. Prints every failure with file:line, then a summary per area,
and exits 1 if anything failed (build.sh refuses to build then).

    python3 tests/run-all.py              everything (about 2-4 minutes; the Toolbox suite is the slowest part)
    python3 tests/run-all.py -v           also list every passing test
    python3 tests/run-all.py --only A,B,D run only some areas (letters below)

Areas
  A  playbook.conf: XML, version/title, SupportedBuilds, pages (<= 4 options, description 50-85), option names,
     UseKernelDriver false, uac-no-prompt off by default, every option used; expected.json / options.yml if present
  B  YAML task files: parse with AME tags, the AME schema of every action (types, enums, startup 0-4, runas,
     errorAction, handleExitCodes), option references, !task paths, !run scripts and their parameters, contradictions,
     the owner's safety rules (Defender, SmartScreen, VBS/HVCI, TPM, Secure Boot, SysMain, Game Mode, 0x18, UAC)
  C  Undo consistency: Save-State / the Undo allow-list (computed by DomainOS-Common.ps1 itself in pwsh) cover every
     value, service and task; registryKey and script steps each have an undo story; legacy lists sane
  D  PowerShell static analysis with PowerShell's own parser: parse errors, Windows PowerShell 5.1 compatibility,
     $null into .NET string parameters, UTF-8 BOM, %USERNAME% in AME-run scripts, forbidden commands, tool copies
  E  Pester: DomainOS-Common, Save-State, Undo-DomainOS, Undo-AsSystem, Install-DomainOS run in a sandbox with
     a fake registry / tasks / services (tests/pester)
  F  Guide pages: whats-new.html (version, both languages) and guide.html (generated by New-DriverGuide.ps1 with fake
     hardware) executed in node with a small DOM
  G  Toolbox: dotnet test of DomainScheduler.Tests
  H  Discord bot: is_command, three-way merge, group_of, attachment limits, parse() on real summaries
  I  the built Domain-OS-<version>.apbx (if there): opens with the AME password, holds every referenced file
  J  website + update feeds (gh-pages checkout): HTML, scripts, CSP hashes, local links, feed signatures
  K  DomainSchedTest: builds; its summary format still matches the bot's parse()
  L  GitHub workflows (pinned actions, permissions, secrets) and the status card renderer

Paths can be changed with environment variables: DOS_SCRATCH (sample results, bot repo, site checkout), DOS_TOOLBOX,
DOS_SCHEDTEST, DOS_PWSH, DOS_DOTNET_ROOT. Nothing here needs the network or a token; Pester comes from tests/.vendor.
"""
import argparse, json, os, shutil, subprocess, sys, tempfile, threading, time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, 'lib'))
import ame  # noqa: E402
from framework import Results, Timer, PASS, FAIL, SKIP, INFO  # noqa: E402
import areas_playbook as AP  # noqa: E402
import areas_ext as AX  # noqa: E402

REPO = os.path.dirname(HERE)
HOME = os.path.expanduser('~')
SCRATCH = os.environ.get('DOS_SCRATCH', '/tmp/claude-1006/-home-ars-threadPriority/d8bc5329-2157-4502-928c-8c27d93afb1f/scratchpad')


class Ctx:
    pass


def find_pwsh():
    for p in (os.environ.get('DOS_PWSH'), os.path.join(HOME, 'sdk', 'pwsh', 'pwsh'), shutil.which('pwsh')):
        if p and os.path.exists(p):
            return p
    return None


def background(cmd, env, cwd=None, timeout=1800):
    """Starts cmd in a thread; returns a function that waits and gives (exit code, output, None, seconds)."""
    box = {}

    def run():
        t = time.time()
        try:
            r = subprocess.run(cmd, capture_output=True, text=True, env=env, cwd=cwd, timeout=timeout)
            box['r'] = (r.returncode, r.stdout + r.stderr, None, time.time() - t)
        except Exception as e:
            box['r'] = (-1, f'{type(e).__name__}: {e}', None, time.time() - t)
    th = threading.Thread(target=run, daemon=True)
    th.start()

    def wait():
        th.join()
        return box['r']
    return wait


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('-v', '--verbose', action='store_true')
    ap.add_argument('--only', default='', help='comma-separated area letters, e.g. A,B,D')
    args = ap.parse_args()
    only = {x.strip().upper() for x in args.only.split(',') if x.strip()}
    want = lambda a: not only or a in only
    t0 = time.time()
    R = Results(verbose=args.verbose)
    ctx = Ctx()
    ctx.repo, ctx.tests = REPO, HERE
    ctx.tmp = tempfile.mkdtemp(prefix='dos-tests-')
    ctx.scratch = SCRATCH
    ctx.toolbox = os.environ.get('DOS_TOOLBOX', '/home/ars/threadPriority/DomainScheduler')
    ctx.schedtest = os.environ.get('DOS_SCHEDTEST', '/home/ars/threadPriority/DomainSchedTest/src/DomainSchedTest')
    ctx.gh = os.path.join(SCRATCH, 'repo-main', '.github')
    ctx.bot = os.path.join(ctx.gh, 'discord-bot', 'bot.py')
    ctx.site = os.path.join(SCRATCH, 'ghp')
    ctx.updater_cs = os.path.join(ctx.toolbox, 'src', 'DomainScheduler.Lib', 'Updater.cs')
    dotnet_root = os.environ.get('DOS_DOTNET_ROOT', os.environ.get('DOTNET_ROOT', os.path.join(HOME, 'sdk', 'dotnet')))
    env = dict(os.environ, DOTNET_ROOT=dotnet_root, PATH=dotnet_root + os.pathsep + os.environ.get('PATH', ''),
               DOTNET_CLI_TELEMETRY_OPTOUT='1', DOTNET_NOLOGO='1', POWERSHELL_TELEMETRY_OPTOUT='1', POWERSHELL_UPDATECHECK='Off')
    for k in ('DISCORD_TOKEN', 'GH_PUSH_TOKEN', 'GH_TOKEN', 'GITHUB_TOKEN'):
        env.pop(k, None)
    ctx.env = env
    ctx.pwsh = find_pwsh()
    dotnet = shutil.which('dotnet', path=env['PATH'])
    print(f'Domain OS tests  repo {REPO}\n  pwsh {ctx.pwsh or "MISSING"}  dotnet {dotnet or "MISSING"}  node {shutil.which("node") or "MISSING"}\n', flush=True)

    # slow parts start first, in the background
    waits = {}
    if want('E') and ctx.pwsh:
        nunit = os.path.join(ctx.tmp, 'pester.xml')
        w = background([ctx.pwsh, '-NoProfile', '-NonInteractive', '-File', os.path.join(HERE, 'pester', 'run.ps1'), '-Out', nunit], env, timeout=1200)
        waits['E'] = lambda w=w: (lambda r: (r[0], r[1], nunit, r[3]))(w())
    if want('G') and dotnet and os.path.isdir(ctx.toolbox):
        trxdir = os.path.join(ctx.tmp, 'trx')
        w = background([dotnet, 'test', os.path.join(ctx.toolbox, 'tests', 'DomainScheduler.Tests'), '-c', 'Release', '--nologo',
                        '--logger', 'trx;LogFileName=toolbox.trx', '--results-directory', trxdir], env, timeout=1800)
        waits['G'] = lambda w=w: (lambda r: (r[0], r[1], os.path.join(trxdir, 'toolbox.trx'), r[3]))(w())
    if want('K') and dotnet and os.path.isdir(ctx.schedtest):
        waits['K'] = background([dotnet, 'build', ctx.schedtest, '-p:EnableWindowsTargeting=true', '--nologo', '-v', 'q',
                                 '-o', os.path.join(ctx.tmp, 'schedtest-out')], env, timeout=900)

    # the playbook model and the static PowerShell analysis are shared by several areas
    pbdir = os.path.join(REPO, 'playbook')
    try:
        ctx.pb = ame.Playbook(pbdir)
    except Exception as e:
        R.add('A playbook.conf', 'playbook.conf and task files load', FAIL, f'{type(e).__name__}: {e}')
        ctx.pb = None
    ctx.ps_files = sorted(set(
        [os.path.join(pbdir, 'Executables', f) for f in os.listdir(os.path.join(pbdir, 'Executables')) if f.endswith('.ps1')] +
        [os.path.join(pbdir, 'Executables', 'Guide', f) for f in os.listdir(os.path.join(pbdir, 'Executables', 'Guide')) if f.endswith('.ps1')]))
    ctx.static, ctx.static_error = {}, None
    if ctx.pwsh:
        r = subprocess.run([ctx.pwsh, '-NoProfile', '-NonInteractive', '-File', os.path.join(HERE, 'ps', 'Static.ps1')] + ctx.ps_files,
                           capture_output=True, text=True, env=env, timeout=300)
        try:
            ctx.static = json.loads(r.stdout)
        except Exception:
            ctx.static_error = (r.stdout + r.stderr)[-2000:]
    else:
        ctx.static_error = 'PowerShell 7 (pwsh) not found: set DOS_PWSH'

    def area(letter, fn, *a):
        if not want(letter):
            return
        print(f'--- {letter} ---', flush=True)
        with Timer(R, letter):
            try:
                fn(R, ctx, *a)
            except Exception as e:
                import traceback
                R.add(f'{letter} (runner)', 'area crashed', FAIL, f'{type(e).__name__}: {e}\n{traceback.format_exc(limit=4)}')

    if ctx.pb:
        area('A', AP.area_A)
        area('B', AP.area_B)
        if ctx.pwsh:
            area('C', AP.area_C)
        elif want('C'):
            R.add(AP.C, 'pwsh', FAIL, 'PowerShell 7 not found')
        area('D', AP.area_D)
        area('F', AP.area_F)
        area('I', AP.area_I)
    area('H', AX.area_H)
    area('J', AX.area_J)
    area('L', AX.area_L)
    if want('E'):
        if 'E' in waits:
            area('E', AP.area_E, waits['E']())
        else:
            R.add(AP.E, 'Pester', FAIL, 'PowerShell 7 not found')
    if want('G'):
        area('G', AX.area_G, waits['G']() if 'G' in waits else None)
    if want('K'):
        area('K', AX.area_K, waits['K']() if 'K' in waits else None)
    shutil.rmtree(ctx.tmp, ignore_errors=True)
    return R.summary(time.time() - t0)


if __name__ == '__main__':
    sys.exit(main())
